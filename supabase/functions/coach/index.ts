// Pulse coach (Phase 9): the in-app chat. The app sends the conversation; this function adds
// the user's recent Pulse summaries and asks Claude.
//
// Why a server function and not a direct call from the app:
//   The Anthropic API key must never be inside the app (anyone could extract it from the app
//   file). It lives only here, as a Supabase secret named ANTHROPIC_API_KEY.
//
// Security:
//   * Only signed-in users can call it (Supabase checks the token before this code runs).
//   * The data given to Claude is read with the caller's own token, so Row Level Security limits
//     it to their rows.
//   * A daily request cap per user protects the API bill if a token is ever stolen.
//   * Strava rule (API Policy June 2026, section 5.3): no data from Strava may be put in an AI
//     prompt. Pulse never downloads anything from Strava, and this function only reads the three
//     band-data tables, so nothing of Strava's can end up here.

import Anthropic from "npm:@anthropic-ai/sdk@1.8.0";
import { createClient } from "npm:@supabase/supabase-js@2";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL")!;
const SUPABASE_ANON_KEY = Deno.env.get("SUPABASE_ANON_KEY")!;
const SERVICE_ROLE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;

const DAILY_LIMIT = 40; // coach questions per user per day
const MAX_TURNS = 20; // only the most recent messages are sent on
const MAX_CHARS = 4000; // per message

const SYSTEM = `You are the coach inside Pulse, a personal fitness app that reads a wrist band.
You are talking with the app's user about their own data, which follows below as JSON.

What the numbers mean:
- recovery_pct (0-100): last night's HRV, resting heart rate and sleep compared with the user's own
  14-day normal. 50 means exactly normal. recovery_word is Ready (67+), Steady (34-66) or Rest (below 34).
- day_strain (0-21): how hard the heart worked that day. It gets harder to raise the higher it is.
- sleep_minutes vs sleep_need_minutes: actual sleep against what the body needed.
- hrv_rmssd (ms) and resting_hr (bpm) are measured during sleep; baseline_* are the user's normal.
- Pulse does not measure sleep stages, blood oxygen, or anything medical.

How to answer:
- Plain, friendly language. Short: a few sentences, or a short list when comparing days.
- Use the user's actual numbers and dates. Never invent a number that is not in the data.
- If the data does not answer the question, say so.
- If "source" is "simulated", the numbers are demo data generated by the app. Say that clearly
  the first time you use them.
- You give general wellness and training guidance, not medical advice. For symptoms, injuries or
  health worries, tell the user to see a doctor.`;

const reply = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });

interface ChatMessage {
  role: "user" | "assistant";
  content: string;
}

/** Keeps only well-formed, recent, size-limited messages. The app's input is never trusted as is. */
function clean(input: unknown): ChatMessage[] {
  if (!Array.isArray(input)) return [];
  const messages: ChatMessage[] = [];
  for (const item of input.slice(-MAX_TURNS)) {
    const role = (item as ChatMessage)?.role;
    const content = (item as ChatMessage)?.content;
    if ((role === "user" || role === "assistant") && typeof content === "string" && content.trim()) {
      messages.push({ role, content: content.slice(0, MAX_CHARS) });
    }
  }
  // The conversation sent to Claude must start with the user and end with the user's question.
  while (messages.length > 0 && messages[0].role !== "user") messages.shift();
  return messages.length > 0 && messages[messages.length - 1].role === "user" ? messages : [];
}

Deno.serve(async (request) => {
  if (request.method !== "POST") return reply({ error: "method_not_allowed" }, 405);

  const authorization = request.headers.get("Authorization") ?? "";
  const token = authorization.replace(/^Bearer\s+/i, "");
  const supabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
    global: { headers: { Authorization: `Bearer ${token}` } },
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const { data: auth } = await supabase.auth.getUser(token);
  const userID = auth?.user?.id;
  if (!userID) return reply({ error: "unauthorized" }, 401);

  let body: { messages?: unknown };
  try {
    body = await request.json();
  } catch {
    return reply({ error: "invalid_json" }, 400);
  }
  const messages = clean(body.messages);
  if (messages.length === 0) return reply({ error: "no_question" }, 400);

  // Daily cap. The counter table is server-only, so this one call uses the service role.
  const admin = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, { auth: { persistSession: false } });
  const { data: used, error: usageError } = await admin.rpc("bump_coach_usage", { p_user: userID });
  if (usageError) {
    console.error("coach usage", usageError);
    return reply({ error: "server_error" }, 500);
  }
  if ((used as number) > DAILY_LIMIT) {
    return reply({ error: "daily_limit", message: `You've reached today's limit of ${DAILY_LIMIT} questions.` }, 429);
  }

  // The user's last 14 days, read as the user (RLS).
  const since = new Date(Date.now() - 14 * 86_400_000).toISOString();
  const [days, sleeps, workouts] = await Promise.all([
    supabase.from("daily_summary")
      .select("day,recovery_pct,recovery_word,day_strain,sleep_minutes,sleep_need_minutes,resting_hr,hrv_rmssd,baseline_resting_hr,baseline_hrv,explanation,source")
      .order("day", { ascending: false }).limit(14),
    supabase.from("sleep_session")
      .select("start_at,end_at,asleep_minutes,awake_minutes,disturbances,is_nap,source")
      .gte("end_at", since).order("end_at", { ascending: false }),
    supabase.from("workout")
      .select("start_at,end_at,kind,avg_hr,max_hr,strain,zone_seconds,source")
      .gte("start_at", since).order("start_at", { ascending: false }),
  ]);
  if (days.error || sleeps.error || workouts.error) {
    console.error("coach data", days.error ?? sleeps.error ?? workouts.error);
    return reply({ error: "server_error" }, 500);
  }
  const context = JSON.stringify({
    today: new Date().toISOString().slice(0, 10),
    days: days.data,
    sleep_sessions: sleeps.data,
    workouts: workouts.data,
  });

  const anthropic = new Anthropic({ apiKey: Deno.env.get("ANTHROPIC_API_KEY") });
  try {
    // Claude Opus 5.5 (thinking is always on and adaptive on this model). `fallbacks: "default"`
    // lets the API retry on another model if a safety classifier declines the request by mistake.
    const response = await anthropic.beta.messages.create({
      model: "claude-opus-5-5",
      max_tokens: 16000,
      betas: ["server-side-fallback-2026-07-01"],
      fallbacks: "default",
      system: [
        { type: "text", text: SYSTEM },
        { type: "text", text: `The user's Pulse data (JSON, newest first):\n${context}` },
      ],
      messages,
    });

    if (response.stop_reason === "refusal") {
      return reply({ text: "I can't help with that one. Try asking about your recovery, sleep, strain or workouts." });
    }
    let text = "";
    for (const block of response.content) {
      if (block.type === "text") text += block.text;
    }
    return reply({ text: text.trim() || "I don't have an answer for that.", remaining: DAILY_LIMIT - (used as number) });
  } catch (error) {
    if (error instanceof Anthropic.AuthenticationError) {
      console.error("coach: ANTHROPIC_API_KEY is missing or wrong");
      return reply({ error: "not_configured", message: "The coach isn't set up yet (missing API key on the server)." }, 503);
    }
    if (error instanceof Anthropic.RateLimitError) {
      return reply({ error: "busy", message: "The coach is busy. Try again in a minute." }, 429);
    }
    if (error instanceof Anthropic.APIError) {
      console.error("coach: Anthropic API error", error.status, error.message);
      return reply({ error: "upstream", message: "The coach couldn't answer right now." }, 502);
    }
    console.error("coach failure", error);
    return reply({ error: "server_error" }, 500);
  }
});
